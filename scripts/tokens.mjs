// Generates src/app/tokens.css from replica/design/tokens.json.
// Roles become CSS variables, then Tailwind theme colours: bg-surface, text-muted, border-line...
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const tokens = JSON.parse(fs.readFileSync(path.join(root, "replica/design/tokens.json"), "utf8"));

// token role -> Tailwind colour name
const NAMES = {
  bg: "canvas",
  surface: "surface",
  "surface-sunken": "sunken",
  border: "line",
  "border-input": "input",
  text: "fg",
  "text-muted": "muted",
  "nav-bg": "nav",
  "nav-text": "nav-fg",
};

const lines = ["/* Generated by scripts/tokens.mjs from replica/design/tokens.json. Edit the JSON, not this file. */", ":root {"];
const theme = ["@theme inline {"];
for (const [role, value] of Object.entries(tokens.color)) {
  lines.push(`  --${role}: ${value};`);
  theme.push(`  --color-${NAMES[role] ?? role}: var(--${role});`);
}
lines.push(`  --font-sans-stack: ${tokens.font.sans};`, `  --font-mono-stack: ${tokens.font.mono};`);
lines.push("}", "");
theme.push("  --font-sans: var(--font-inter), var(--font-sans-stack);", "  --font-mono: var(--font-mono-stack);");
for (const [name, t] of Object.entries(tokens.type)) {
  theme.push(`  --text-${name}: ${t.size / 16}rem;`, `  --text-${name}--line-height: ${t.line / 16}rem;`);
}
for (const [name, px] of Object.entries(tokens.radius)) theme.push(`  --radius-${name}: ${px}px;`);
for (const [name, v] of Object.entries(tokens.shadow)) theme.push(`  --shadow-${name}: ${v};`);
theme.push(`  --ease-brand: ${tokens.motion.ease};`, "}");

fs.writeFileSync(path.join(root, "src/app/tokens.css"), [...lines, ...theme, ""].join("\n"));
console.log(`tokens.css: ${Object.keys(tokens.color).length} colours, ${Object.keys(tokens.type).length} type sizes`);
